import React, { useState, useEffect } from "react";
import { motion } from "framer-motion";
import { ThumbsUp, ThumbsDown } from "lucide-react";
import "./blog.css";

export default function Blog() {
const defaultPosts = [
  {
    id: 1,
    title: "🚀 Building an AI Resume ATS Scorer",
    text: "One of my favorite projects is an AI-powered ATS Resume Scorer. I implemented semantic similarity, NLP-based resume analysis, ATS scoring, and AI-generated improvement suggestions using FastAPI, Sentence Transformers, and Llama 3. This project strengthened my backend API development and AI integration skills."
  },
  {
  id: 2,
  title: "🎓 Making Attendance Smarter with AI",
  text: "The SnapClass project allowed me to explore face recognition, voice verification, and AI-powered attendance automation. Working with OpenCV, Supabase, and machine learning models showed me how AI can simplify everyday administrative tasks."
},


  {
    id: 3,
    title: "🚖 Building a Full Stack Ride Hailing Web Application",
    text: "Developing an Uber Clone improved my understanding of real-time applications. I implemented JWT authentication, Google Maps integration, Socket.io communication, ride management, and MongoDB to create a scalable MERN architecture."
  },

  {
    id: 4,
    title: "🎵 Creating a Spotify-inspired Music Platform",
    text: "The Symphony Music Streaming project helped me learn state management, authentication, playlist management, responsive UI design, and modern MERN development while building a complete music streaming experience."
  },

  {
    id: 5,
    title: "🤖 Why I'm Focusing on Artificial Intelligence",
    text: "Artificial Intelligence combines mathematics, programming, and real-world problem solving. My goal is to build intelligent systems that improve healthcare, education, and productivity while continuously learning modern AI technologies."
  },

  {
    id: 6,
    title: "💡 My Learning Journey",
    text: "Every project I build teaches me something new. From simple HTML applications to full-stack MERN projects and AI systems, I focus on writing better code, improving architecture, and continuously expanding my technical skills."
  }
];

  const [posts, setPosts] = useState([]);

  useEffect(() => {
    const savedVotes = JSON.parse(localStorage.getItem("kd_blog_votes") || "{}");
    const votedByUser = JSON.parse(localStorage.getItem("kd_blog_voted") || "{}");
    const withVotes = defaultPosts.map((p) => ({
      ...p,
      agree: savedVotes[p.id]?.agree || 0,
      disagree: savedVotes[p.id]?.disagree || 0,
      userVote: votedByUser[p.id] || null,
    }));
    setPosts(withVotes);
  }, []);

  function vote(id, type) {
    const votedByUser = JSON.parse(localStorage.getItem("kd_blog_voted") || "{}");
    if (votedByUser[id]) return;

    const next = posts.map((p) =>
      p.id === id ? { ...p, [type]: p[type] + 1, userVote: type } : p
    );
    setPosts(next);

    const votes = Object.fromEntries(
      next.map((p) => [p.id, { agree: p.agree, disagree: p.disagree }])
    );
    localStorage.setItem("kd_blog_votes", JSON.stringify(votes));
    localStorage.setItem(
      "kd_blog_voted",
      JSON.stringify({ ...votedByUser, [id]: type })
    );
  }

  return (
    <motion.section
      className="blog-section"
      initial={{ opacity: 0 }}
      animate={{ opacity: 1 }}
      transition={{ duration: 0.6 }}
    >
      <motion.h2
        className="blog-title"
        initial={{ y: -15, opacity: 0 }}
        animate={{ y: 0, opacity: 1 }}
        transition={{ duration: 0.6 }}
      >
        📝 My Blog
      </motion.h2>
      <p className="blog-sub">
        Personal thoughts, experiences, and reflections — feel free to react!
      </p>

      <div className="blog-grid">
        {posts.map((p, idx) => (
          <motion.div
            key={p.id}
            className="blog-post"
            initial={{ opacity: 0, y: 40 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.6, delay: idx * 0.15 }}
            whileHover={{
              scale: 1.02,
              boxShadow: "0 0 20px rgba(255,255,255,0.1)",
            }}
          >
            <h3 className="post-title">{p.title}</h3>
            <p className="post-text">{p.text}</p>

            <div className="vote-container">
              <motion.button
                onClick={() => vote(p.id, "agree")}
                disabled={!!p.userVote}
                whileTap={{ scale: 0.85 }}
                whileHover={{ scale: 1.15 }}
                className={`vote-btn-circle agree ${
                  p.userVote === "agree" ? "active" : ""
                }`}
              >
                <ThumbsUp size={20} />
                <motion.span
                  key={p.agree}
                  initial={{ opacity: 0, y: -4 }}
                  animate={{ opacity: 1, y: 0 }}
                  className="vote-count"
                >
                  {p.agree}
                </motion.span>
              </motion.button>

              <motion.button
                onClick={() => vote(p.id, "disagree")}
                disabled={!!p.userVote}
                whileTap={{ scale: 0.85 }}
                whileHover={{ scale: 1.15 }}
                className={`vote-btn-circle disagree ${
                  p.userVote === "disagree" ? "active" : ""
                }`}
              >
                <ThumbsDown size={20} />
                <motion.span
                  key={p.disagree}
                  initial={{ opacity: 0, y: -4 }}
                  animate={{ opacity: 1, y: 0 }}
                  className="vote-count"
                >
                  {p.disagree}
                </motion.span>
              </motion.button>
            </div>
          </motion.div>
        ))}
      </div>
    </motion.section>
  );
}
